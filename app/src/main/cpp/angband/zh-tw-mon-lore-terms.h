static inline const char *angdroid_zh_tw_lore_lookup(const char *en,
        const struct angdroid_lore_term *pairs, size_t count, int zh_tw)
{
    size_t i;
    if (!en || !zh_tw) return en;
    for (i = 0; i < count; i++)
        if (strcmp(en, pairs[i].en) == 0) return pairs[i].zh;
    return en;
}
