static unsigned checked;
#define CHECK(expr) do { if (!(expr)) { \
    fprintf(stderr, "FAIL line %d: %s\n", __LINE__, #expr); \
    return 1; } ++checked; } while (0)

int main(void)
{
    const char *unknown = "{name} sings an unrecognized alternate spell.";
    char output[120];
    size_t i;

    CHECK(sizeof expected / sizeof expected[0] == 221);
    for (i = 0; i < sizeof expected / sizeof expected[0]; ++i) {
        CHECK(strcmp(angdroid_fa_spell_message_locale(expected[i].english,
            true), expected[i].chinese) == 0);
        CHECK(angdroid_fa_spell_message_locale(expected[i].english,
            false) == expected[i].english);
        CHECK(strlen(expected[i].chinese) < 1024);
    }
    CHECK(angdroid_fa_spell_message_locale(unknown, true) == unknown);
    CHECK(angdroid_fa_spell_message_locale(NULL, true) == NULL);
    CHECK(angdroid_fa_spell_message_locale(unknown, false) == unknown);

    CHECK(strcmp(angdroid_fa_spell_subject("The orc", true,
        output, sizeof output), "這隻orc") == 0);
    CHECK(strcmp(angdroid_fa_spell_subject("the hill troll", true,
        output, sizeof output), "這隻hill troll") == 0);
    CHECK(strcmp(angdroid_fa_spell_subject("it", true,
        output, sizeof output), "牠") == 0);
    CHECK(strcmp(angdroid_fa_spell_subject("something", true,
        output, sizeof output), "某個東西") == 0);
    CHECK(angdroid_fa_spell_subject("The orc", false, output,
        sizeof output) != output);
    CHECK(angdroid_fa_spell_subject("Wormtongue", true, output,
        sizeof output) != output);
    CHECK(angdroid_fa_spell_subject(NULL, true, output,
        sizeof output) == NULL);
    CHECK(strcmp(angdroid_fa_spell_message_locale(
        "{name} breathes fire.", true), "{name}吐出火焰。") == 0);
    CHECK(strcmp(angdroid_fa_spell_message_locale(
        "{name} slings a pebble, but misses.", true),
        "{name}投擲石子，但沒有擊中。") == 0);
    CHECK(strcmp(angdroid_fa_spell_message_locale(
        "You resist the effects!", true), "你抵抗了這次效果！") == 0);

    printf("PASS: %u source-exact FA spell notification C99 checks\n",
        checked);
    return 0;
}
